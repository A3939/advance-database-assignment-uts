import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
test.beforeEach(async ({ page }) => { await page.emulateMedia({ reducedMotion: "reduce" }); });
const batch = "bcc5da57-25f2-41ec-9925-bef421b02671";
const scope = (path = "/", from = "2024-01-01", to = "2024-12-31", extra = "") => `${path}?source=NSW&from=${from}&to=${to}&batchId=${batch}&datasetVersion=official-v1${extra}`;
test("partial-year evidence and actual Overview JSON download retain month scope", async ({ page }) => {
  await page.goto(scope("/", "2024-03-01", "2024-03-31"));
  await expect(page.getByText("Recorded crashes · Mar 2024", {exact:true})).toBeVisible();
  await expect(page.locator(".metric-value").first()).toHaveText("1,601");
  await page.getByRole("button", { name: "Trend chart evidence" }).click();
  await expect(page.getByRole("dialog")).toContainText("2024 · Mar subtotal (1/1 months)");
  await page.keyboard.press("Escape");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", {name:"Export",exact:true}).click();
  const download = await downloadPromise;
  await download.saveAs("output/playwright/overview-march.json");
  const data = JSON.parse(await readFile((await download.path())!, "utf8"));
  expect(data.filters.dateRange).toEqual({from:"2024-03-01",to:"2024-03-31"});
  expect(data.overview.data.crashes.value).toBe(1601);
  expect(data.timeSeries.data[0]).toMatchObject({ selectedMonths:[3], observedMonths:1, fullYear:false });
  await page.getByRole("link", { name: "Compare matching months in Analytics" }).click();
  await expect(page).toHaveURL(/\/analytics\?.*from=2024-03-01/);
  await expect(page.getByRole("heading", {name:"Mar 2024 details"})).toBeVisible();
  await expect(page.getByRole("heading", {name:"Typical month"})).toHaveCount(0);
});
test("metric-linked comparison, refresh, back-forward and Analytics download", async ({ page }) => {
  await page.goto(scope("/analytics"));
  await expect(page.getByText("+1.2%", {exact:true})).toBeVisible();
  await page.getByRole("region", {name:"Time and change"}).getByRole("button", {name:"Lives lost",exact:true}).click();
  await expect(page.getByRole("heading", {name:"Lives lost year-on-year"})).toBeVisible();
  await expect(page.getByText("-3.8%", {exact:true})).toBeVisible();
  await expect(page).toHaveURL(/metric=livesLost/);
  await page.reload();
  await expect(page.getByText("-3.8%", {exact:true})).toBeVisible();
  await page.getByRole("region", {name:"Time and change"}).getByRole("button", {name:"Fatal crashes",exact:true}).click();
  await expect(page.getByText("-1.7%", {exact:true})).toBeVisible();
  await page.goBack();
  await expect(page.getByRole("region", {name:"Time and change"}).getByRole("button", {name:"Lives lost",exact:true})).toHaveAttribute("aria-pressed","true");
  await page.goForward();
  await expect(page.getByRole("region", {name:"Time and change"}).getByRole("button", {name:"Fatal crashes",exact:true})).toHaveAttribute("aria-pressed","true");
  const pending = page.waitForEvent("download");
  await page.getByRole("button", {name:"Export",exact:true}).click();
  const exportFile = await pending; await exportFile.saveAs("output/playwright/analytics-four-metrics.json");
  const result = JSON.parse(await readFile((await exportFile.path())!,"utf8"));
  expect(result.view.metric).toBe("fatalCrashes");
  expect(result.analysis.data.yearly[0].comparisons.livesLost).toMatchObject({current:327,previous:340});
});
