test("heatmap visibly distinguishes known zero, unknown, no coverage and outside selection", async ({page}) => {
  await page.route("**/api/data/overview?**", async route => {
    const response=await route.fetch(); const body=await response.json();
    body.data.crashes.value=null; body.data.crashes.availability="unknown";
    await route.fulfill({response,json:body});
  });
  await page.route("**/api/data/timeseries?**",async route=>{
    const response=await route.fetch(); const body=await response.json();
    body.data=body.data.map((row: {period:string;crashes:number|null})=>row.period==="2020-01"?{...row,crashes:0}:row.period==="2020-02"?{...row,crashes:null}:row);
    await route.fulfill({response,json:body});
  });
  await page.goto(scope("/analytics","2019-12-01","2020-02-29"));
  await expect(page.getByRole("button",{name:"Dec 2019: No coverage",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Jan 2020: 0 crashes",exact:true})).toHaveText("0");
  await expect(page.getByRole("button",{name:"Feb 2020: Unknown count",exact:true})).toHaveText("?");
  await expect(page.getByRole("button",{name:"Mar 2020: Not in selected period",exact:true})).toHaveText("Out");
});
