test("delayed stale requests cannot label NSW values as VIC, and retry retains scope", async ({ page }) => {
  await page.goto(scope());
  await expect(page.locator(".metric-value").first()).toHaveText("18,939");
  await page.route("**/api/data/**", async route => {
    const u=new URL(route.request().url());
    if(u.searchParams.get("source")==="VIC") { await new Promise(resolve=>setTimeout(resolve,700)); }
    await route.continue().catch(()=>{});
  });
  await page.getByLabel("Data source",{exact:true}).click();
  await page.getByRole("option", { name: "VIC", exact: true }).click();
  await expect(page.locator(".metric-value").first()).toHaveText("—");
  await expect(page.getByRole("button",{name:"Crashes definition",exact:true})).toBeDisabled();
  await page.getByLabel("Data source",{exact:true}).click();
  await page.getByRole("option", { name: "QLD", exact: true }).click();
  await expect(page.locator(".metric-value").first()).toHaveText("14,358");
  await page.unroute("**/api/data/**");
  let failed=false;
  await page.route("**/api/data/overview?**",async route=>{if(!failed){failed=true;await route.fulfill({status:503,body:"unavailable"});}else await route.continue();});
  await page.getByLabel("Data source",{exact:true}).click();
  await page.getByRole("option", { name: "NSW", exact: true }).click();
  await expect(page.locator(".error-banner")).toContainText("could not be loaded");
  await expect(page.getByText("Map unavailable. Retry this selection above.")).toBeVisible();
  await page.getByRole("button",{name:"Retry selection"}).click();
  await expect(page.locator(".metric-value").first()).toHaveText("18,939");
  await expect(page.getByLabel("Data source",{exact:true})).toHaveText("NSW");
});
